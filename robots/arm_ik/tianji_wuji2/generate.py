"""Project the canonical full robot onto its unchanged 14-DoF arm chains.

Run with the project Python from any directory, after compiling the full plant.
This is a kinematics resource, not a second simulation plant: hand descendants
are omitted; base/arm/TCP inertias, transforms and limits come from the URDF.
The world placement comes from the verified compiled plant, not the local URDF.
The virtual solver palm sites deliberately retain the existing teleop contract;
they are not source-URDF links or the Hand2 wrist origins.
"""
from copy import deepcopy
import hashlib
import math
import os
from pathlib import Path
import xml.etree.ElementTree as ET

from simulation.models.model_compiler.artifacts import verify_artifacts


ROOT = Path(__file__).resolve().parent
SOURCE = ROOT.parents[1] / "simulation/tianji_wuji2/urdf/tianji_wuji2.urdf"
PALM_POSITION = "0 -0.1615 0"
PALM_QUATERNION = "0.499998 0.5 -0.5 0.500002"


def quaternion(rpy):
    r, p, y = (float(v) / 2 for v in rpy.split())
    cr, sr, cp, sp, cy, sy = math.cos(r), math.sin(r), math.cos(p), math.sin(p), math.cos(y), math.sin(y)
    return " ".join(format(v, ".17g") for v in (
        cr * cp * cy + sr * sp * sy, sr * cp * cy - cr * sp * sy,
        cr * sp * cy + sr * cp * sy, cr * cp * sy - sr * sp * cy))


def pose(element):
    origin = element.find("origin")
    if origin is None:
        return {}
    return {"pos": origin.get("xyz", "0 0 0"),
            "quat": quaternion(origin.get("rpy", "0 0 0"))}


def generate():
    source = ET.parse(SOURCE).getroot()
    generated = SOURCE.parent.parent / "generated"
    verify_artifacts(generated / "model_manifest.yaml", SOURCE)
    compiled = ET.parse(generated / "unified_plant.xml")
    compiled_root = compiled.find("./worldbody/body[@name='base_link']")
    if compiled_root is None:
        raise ValueError("compiled plant must contain the fixed base_link root")
    root_pose = {key: compiled_root.get(key, default)
                 for key, default in (("pos", "0 0 0"), ("quat", "1 0 0 0"))}
    root_collisions = [
        geom for geom in compiled.findall("./worldbody/body[@name='base_link']/geom")
        if geom.get("contype") == "1"
    ]
    compiled_meshes = {mesh.get("name"): mesh for mesh in compiled.findall("asset/mesh")}
    links = {"base_link"} | {f"Link{i}_{s}" for s in "LR" for i in range(1, 8)} | {f"TCP_Link_{s}" for s in "LR"}
    projection = ET.Element("robot", name="tianji_wuji2_arms")
    projection.append(ET.Comment("Generated by ../generate.py from the canonical full robot; no hand dynamics."))
    for element in source:
        if ((element.tag == "link" and element.get("name") in links) or
            (element.tag == "joint" and element.find("parent").get("link") in links and element.find("child").get("link") in links)):
            projection.append(deepcopy(element))
    if len(projection.findall("link")) != 17 or len(projection.findall("joint")) != 16:
        raise ValueError("canonical source must provide the base and both seven-joint arms with TCP links")
    urdf = ROOT / "urdf/tianji_wuji2_arms.urdf"
    mjcf = ROOT / "mjcf/tianji_wuji2_arms.xml"
    urdf.parent.mkdir(parents=True, exist_ok=True)
    mjcf.parent.mkdir(parents=True, exist_ok=True)
    for mesh in projection.iter("mesh"):
        mesh.set("filename", os.path.relpath((SOURCE.parent / mesh.get("filename")).resolve(), urdf.parent))

    model = ET.Element("mujoco", model="tianji_wuji2_source_arms_palm_tcp")
    model.append(ET.Comment("Generated by ../generate.py; solver palm is virtual, not the source TCP or wrist."))
    ET.SubElement(model, "compiler", angle="radian", autolimits="true", fusestatic="false", inertiafromgeom="false")
    ET.SubElement(model, "size", nuser_jnt="1")
    asset = ET.SubElement(model, "asset")
    world = ET.SubElement(model, "worldbody")
    by_name = {link.get("name"): link for link in projection.findall("link")}
    children = {}
    for joint in projection.findall("joint"):
        children.setdefault(joint.find("parent").get("link"), []).append(joint)

    def body(parent, name, joint=None):
        link = by_name[name]
        node = ET.SubElement(parent, "body", name=name, **(pose(joint) if joint is not None else root_pose))
        inertial = link.find("inertial")
        if inertial is not None:
            origin = inertial.find("origin")
            if origin is not None and any(float(v) != 0 for v in origin.get("rpy", "0 0 0").split()):
                raise ValueError("nonidentity source inertia axes require explicit tensor rotation")
            inertia = inertial.find("inertia")
            mass = inertial.find("mass").get("value")
            tensor = [inertia.get(k) for k in ("ixx", "iyy", "izz", "ixy", "ixz", "iyz")]
            # URDF's fixed zero-mass TCP is a reference frame, not a positive
            # inertia tensor. inertiafromgeom=false also prevents marker meshes
            # from silently supplying a substitute mass.
            if float(mass) != 0 or any(float(value) != 0 for value in tensor):
                ET.SubElement(node, "inertial", pos=origin.get("xyz", "0 0 0") if origin is not None else "0 0 0",
                              mass=mass, fullinertia=" ".join(tensor))
        if joint is not None and joint.get("type") != "fixed":
            if joint.get("type") != "revolute":
                raise ValueError("arm projection requires scalar revolute joints")
            limit = joint.find("limit")
            ET.SubElement(node, "joint", name=joint.get("name"), type="hinge", axis=joint.find("axis").get("xyz"),
                          range=limit.get("lower") + " " + limit.get("upper"), user=limit.get("velocity"),
                          actuatorfrcrange="-" + limit.get("effort") + " " + limit.get("effort"))
        for kind in ("visual", "collision"):
            if name == "base_link" and kind == "collision":
                # Share the verified source-component collisions with the
                # physical plant; never recreate a whole-assembly convex hull.
                for index, geometry in enumerate(root_collisions):
                    source_mesh = compiled_meshes[geometry.get("mesh")]
                    mesh_name = f"{name}_collision_{index}"
                    attributes = dict(source_mesh.attrib)
                    attributes.update(name=mesh_name, file=os.path.relpath(
                        (generated / source_mesh.get("file")).resolve(), mjcf.parent))
                    ET.SubElement(asset, "mesh", **attributes)
                    attributes = dict(geometry.attrib)
                    attributes.update(mesh=mesh_name, group="3", rgba="0 0 0 0")
                    ET.SubElement(node, "geom", **attributes)
                continue
            for index, geometry in enumerate(link.findall(kind)):
                mesh = geometry.find("geometry/mesh")
                if mesh is None:
                    raise ValueError("arm projection expects source mesh geometry")
                mesh_name = f"{name}_{kind}_{index}"
                attributes = {"name": mesh_name, "file": os.path.relpath((urdf.parent / mesh.get("filename")).resolve(), mjcf.parent)}
                if mesh.get("scale"):
                    attributes["scale"] = mesh.get("scale")
                ET.SubElement(asset, "mesh", inertia="shell", **attributes)
                attributes = {"type": "mesh", "mesh": mesh_name, **pose(geometry)}
                if kind == "visual":
                    attributes.update(contype="0", conaffinity="0", group="2")
                    color = geometry.find("material/color")
                    if color is not None:
                        attributes["rgba"] = color.get("rgba")
                else:
                    attributes.update(group="3", rgba="0 0 0 0")
                ET.SubElement(node, "geom", **attributes)
        if name in ("Link7_L", "Link7_R"):
            ET.SubElement(node, "site", name="tcp_" + name[-1], pos=PALM_POSITION,
                          quat=PALM_QUATERNION, size="0.008", rgba="1 0.2 0.2 1")
        for child in children.get(name, ()):
            body(node, child.find("child").get("link"), child)

    body(world, "base_link")
    for side in "LR":
        target = ET.SubElement(world, "body", name="target_" + side, mocap="true")
        ET.SubElement(target, "geom", type="sphere", size="0.015", contype="0", conaffinity="0", rgba="1 0.8 0.1 0.5")
    for path, tree in ((urdf, projection), (mjcf, model)):
        ET.indent(tree, space="  ")
        ET.ElementTree(tree).write(path, encoding="utf-8", xml_declaration=True)
        print(path.name, hashlib.sha256(path.read_bytes()).hexdigest())
    print("canonical_source_sha256", hashlib.sha256(SOURCE.read_bytes()).hexdigest())


if __name__ == "__main__":
    generate()
